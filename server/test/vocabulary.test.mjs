import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { test } from "node:test";
import { JournalStore } from "../dist/store.js";
import { writeSchema } from "../dist/domain.js";
import { definitionSchema } from "../dist/function-contract.js";

const write = change => writeSchema.parse({ requestID: randomUUID(), actor: "River", source: "Agent", change });
const declare = (id, definition, expectedRevision = 0) => ({ operation: "defineType", itemID: id, definition, expectedRevision });

test("open names, type revisions and fields survive journal replay; legacy snapshots stay readable", t => {
  const db = new JournalStore(":memory:");
  const imported = new JournalStore(":memory:");
  t.after(() => { db.close(); imported.close(); });
  const apply = change => db.append(write(change));
  const experiment = { family: "item", label: "实验", base: "idea", defaultStatus: "采样", fields: { samples: { type: "number" } } };
  const declaration = write(declare("experiment", experiment));
  assert.equal(db.append(declaration).created, true);
  assert.equal(db.append(declaration).created, false);
  assert.throws(() => apply(declare("experiment", experiment)), /revision/);
  apply(declare("category", { family: "category" }));
  apply(declare("passed", { family: "event", fields: { score: { type: "number" } } }));
  apply({ operation: "create", itemID: "one", kind: "experiment", title: "访谈", fields: { samples: 10, extra: ["开发", false] } });
  assert.throws(() => apply(declare("experiment", { ...experiment, base: "direction" }, 1)), /base/);
  assert.throws(() => apply({ operation: "update", itemID: "one", fields: { samples: "ten" } }), /expects number/);
  assert.throws(() => apply({ operation: "passed", itemID: "one", payload: { score: null } }), /expects number/);
  const payload = { score: 0.9, context: { tags: ["a", null] } };
  apply({ operation: "passed", itemID: "one", fields: { extra: null, reviewed: true }, payload });
  apply({ operation: "create", kind: "主题", itemID: "root", title: "主题" });
  apply({ operation: "create", kind: "访谈", itemID: "child", parentID: "root", title: "陪访" });
  assert.throws(() => apply({ operation: "update", itemID: "root", parentID: "child" }), /cycle/);
  assert.throws(() => apply({ operation: "update", itemID: "root", parentID: "unknown" }), /parent/);
  const original = db.snapshot(null);
  const { workspace } = original.body;
  assert.equal(workspace.items.one.status, "采样");
  assert.deepEqual(workspace.items.one.fields, { samples: 10, reviewed: true });
  assert.deepEqual(workspace.entries.find(e => e.change.operation === "passed").change.payload, payload);
  assert.equal(workspace.definitions["item:experiment"].revision, 1);
  assert.deepEqual(Object.keys(workspace.items).sort(), ["child", "one", "root"]);
  imported.import(workspace.entries);
  assert.deepEqual(imported.snapshot(null).body, original.body);
  const older = db.snapshot(null, original.etag, false);
  assert.notEqual(older.etag, original.etag);
  assert.deepEqual(Object.keys(older.body.workspace.items), ["one"]);
  assert.deepEqual(older.body.workspace.entries.map(e => e.change.operation), ["create", "update"]);
  assert.equal(older.body.workspace.items.one.kind, "idea");
});

test("a hosted function reads a custom event and fields; a named trigger pins its scheduling source", async t => {
  const db = new JournalStore(":memory:");
  t.after(() => db.close());
  const now = Date.parse("2026-01-08T12:00:00Z");
  const apply = change => db.append(write(change), now);
  apply({ operation: "create", kind: "实验", itemID: "E", title: "复验", fields: { count: 7 } });
  const source = { kind: "event", operation: "复验通过", delaySeconds: 1 };
  apply(declare("实验复核", { family: "trigger", source }));
  const definition = definitionSchema.parse({ name: "复核", trigger: { kind: "实验复核" },
    code: "return [{operation:'已汇总',itemID:ctx.item.id,fields:{total:ctx.item.fields.count+ctx.event.change.payload.extra}}]" });
  const publish = rev => db.functions.deploy("review", rev, definition, "River", now);
  assert.equal(publish(0).triggerRevision, 1);
  apply(declare("实验复核", { family: "trigger", source: { kind: "cron", expression: "0 9 * * *", timezone: "Asia/Shanghai" } }, 1));
  assert.equal(publish(0).triggerRevision, 1);
  apply({ operation: "复验通过", itemID: "E", payload: { extra: 5 } });
  assert.equal(await db.functions.tick(() => now), false);
  assert.equal(await db.functions.tick(() => now + 1000), true);
  assert.equal(db.functions.get("review").runs[0].status, "succeeded");
  assert.equal(db.snapshot(null).body.workspace.items.E.fields.total, 12);
  assert.equal(db.functions.setEnabled("review", 1, false, "River", now).triggerRevision, 1);
  assert.equal(db.functions.setEnabled("review", 2, true, "River", now).resolvedTrigger.kind, "event");
  const republished = publish(3);
  assert.equal(republished.triggerRevision, 2);
  assert.equal(republished.resolvedTrigger.kind, "cron");
  assert.ok(Date.parse(republished.nextAt) > now);
  const direct = definitionSchema.parse({ name: "直接订阅", trigger: { kind: "验收完成" }, code: "return []" });
  assert.equal(db.functions.deploy("direct", 0, direct, "Jun", now).resolvedTrigger.operation, "验收完成");
  apply({ operation: "验收完成", itemID: "E" });
  await db.functions.tick(() => now);
  assert.equal(db.functions.get("direct").runs[0].status, "skipped");
});
